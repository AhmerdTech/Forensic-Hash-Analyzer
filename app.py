# ---------------------------------------------------------
# HASH CALCULATION
# ---------------------------------------------------------

def calculate_hashes(file_path):
    md5 = hashlib.md5()
    sha1 = hashlib.sha1()
    sha256 = hashlib.sha256()

    with open(file_path, "rb") as file:
        while True:
            data = file.read(4096)

            if not data:
                break

            md5.update(data)
            sha1.update(data)
            sha256.update(data)

    return (
        md5.hexdigest(),
        sha1.hexdigest(),
        sha256.hexdigest(),
    )


# ---------------------------------------------------------
# PDF REPORT
# ---------------------------------------------------------

def create_pdf_report(
    case_id,
    evidence_id,
    examiner,
    description,
    file_name,
    file_size,
    created,
    modified,
    md5,
    sha1,
    sha256,
):
    report_file = tempfile.NamedTemporaryFile(
        delete=False,
        suffix=".pdf"
    )

    report_file.close()

    document = SimpleDocTemplate(
        report_file.name,
        pagesize=A4,
        rightMargin=20 * mm,
        leftMargin=20 * mm,
        topMargin=20 * mm,
        bottomMargin=20 * mm,
    )

    styles = getSampleStyleSheet()

    story = []

    story.append(
        Paragraph(
            "FORENSIC ANALYSIS REPORT",
            styles["Title"]
        )
    )

    story.append(Spacer(1, 12))

    story.append(
        Paragraph(
            "Case Information",
            styles["Heading2"]
        )
    )

    case_data = [
        ["Case ID", case_id],
        ["Evidence ID", evidence_id],
        ["Examiner", examiner],
        ["Description", description],
    ]

    case_table = Table(
        case_data,
        colWidths=[45 * mm, 115 * mm]
    )

    case_table.setStyle(
        TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
            ("BACKGROUND", (0, 0), (0, -1), colors.lightgrey),
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ])
    )

    story.append(case_table)
    story.append(Spacer(1, 15))

    story.append(
        Paragraph(
            "Evidence Information",
            styles["Heading2"]
        )
    )

    file_data = [
        ["File Name", file_name],
        ["File Size", f"{file_size} bytes"],
        ["Created", str(created)],
        ["Modified", str(modified)],
        [
            "Analysis Time",
            datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        ],
    ]

    file_table = Table(
        file_data,
        colWidths=[45 * mm, 115 * mm]
    )

    file_table.setStyle(
        TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
            ("BACKGROUND", (0, 0), (0, -1), colors.lightgrey),
            ("FONTNAME", (0, 0), (0, -1), "Helvetica-Bold"),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ])
    )

    story.append(file_table)
    story.append(Spacer(1, 15))

    story.append(
        Paragraph(
            "Cryptographic Hashes",
            styles["Heading2"]
        )
    )

    hash_data = [
        ["Algorithm", "Hash Value"],
        ["MD5", md5],
        ["SHA-1", sha1],
        ["SHA-256", sha256],
    ]

    hash_table = Table(
        hash_data,
        colWidths=[45 * mm, 115 * mm]
    )

    hash_table.setStyle(
        TableStyle([
            ("GRID", (0, 0), (-1, -1), 0.5, colors.black),
            ("BACKGROUND", (0, 0), (-1, 0), colors.lightgrey),
            ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
            ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ])
    )

    story.append(hash_table)
    story.append(Spacer(1, 20))

    story.append(
        Paragraph(
            "Generated by Forensic File Analyzer.",
            styles["BodyText"]
        )
    )

    document.build(story)

    with open(report_file.name, "rb") as pdf:
        pdf_data = pdf.read()

    os.unlink(report_file.name)

    return pdf_data


