st.header("📁 Case Information")

col1, col2 = st.columns(2)

with col1:
    case_id = st.text_input(
        "Case ID",
        placeholder="Example: CASE-001"
    )

    evidence_id = st.text_input(
        "Evidence ID",
        placeholder="Example: EVID-001"
    )

with col2:
    examiner = st.text_input(
        "Examiner Name",
        placeholder="Enter examiner name"
    )

    description = st.text_area(
        "Evidence Description",
        placeholder="Describe the evidence..."
    )


# ---------------------------------------------------------
# FILE UPLOAD
# ---------------------------------------------------------

st.header("📤 Evidence File")

uploaded_file = st.file_uploader(
    "Upload an evidence file for analysis",
    type=None,
)

if uploaded_file is not None:

    st.success(
        f"File selected: {uploaded_file.name}"
    )

    if st.button(
        "🔍 Analyze Evidence",
        use_container_width=True
    ):

        with st.spinner("Analyzing evidence..."):

            with tempfile.NamedTemporaryFile(
                delete=False
            ) as temp_file:

                temp_file.write(
                    uploaded_file.getbuffer()
                )

                temp_path = temp_file.name

            try:

                file_info = os.stat(temp_path)

                created = datetime.fromtimestamp(
                    file_info.st_ctime
                )

                modified = datetime.fromtimestamp(
                    file_info.st_mtime
                )

                md5, sha1, sha256 = calculate_hashes(
                    temp_path
                )

                st.success(
                    "Analysis completed successfully."
                )

                # -------------------------------------------------
                # FILE INFORMATION
                # -------------------------------------------------

                st.header("📊 Analysis Results")

                info1, info2, info3 = st.columns(3)

                with info1:
                    st.metric(
                        "File Size",
                        f"{file_info.st_size} bytes"
                    )

                with info2:
                    st.metric(
                        "Evidence ID",
                        evidence_id or "Not provided"
                    )

                with info3:
                    st.metric(
                        "Case ID",
                        case_id or "Not provided"
                    )

                st.subheader("📄 File Information")

                st.write(
                    f"**File Name:** {uploaded_file.name}"
                )

                st.write(
                    f"**Created:** {created}"
                )

                st.write(
                    f"**Modified:** {modified}"
                )

                # -------------------------------------------------
                # HASHES
                # -------------------------------------------------

                st.subheader("🔐 Cryptographic Hashes")

                hash_col1, hash_col2, hash_col3 = st.columns(3)

                with hash_col1:
                    st.caption("MD5")
                    st.code(md5)

                with hash_col2:
                    st.caption("SHA-1")
                    st.code(sha1)

                with hash_col3:
                    st.caption("SHA-256")
                    st.code(sha256)

                # -------------------------------------------------
                # PDF
                # -------------------------------------------------

                pdf_data = create_pdf_report(
                    case_id,
                    evidence_id,
                    examiner,
                    description,
                    uploaded_file.name,
                    file_info.st_size,
                    created,
                    modified,
                    md5,
                    sha1,
                    sha256,
                )

                st.subheader("📄 Forensic Report")

                st.download_button(
                    label="⬇️ Download Forensic PDF Report",
                    data=pdf_data,
                    file_name=(
                        f"{case_id}_{evidence_id}"
                        "_forensic_report.pdf"
                    ),
                    mime="application/pdf",
                    use_container_width=True,
                )

            finally:
                os.unlink(temp_path)


